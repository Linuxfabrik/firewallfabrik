def test_iptables_save_header_names_the_family_and_release():
    ruleset = parse_iptables_save(
        '# Generated by ip6tables-save v1.8.11 on Wed Oct  1 10:00:00 2026\n'
        '*filter\n:INPUT DROP [0:0]\n-A INPUT -s 2001:db8::/32 -j ACCEPT\nCOMMIT\n'
    )
    table = ruleset.tables[0]
    assert ruleset.version == '1.8.11'
    assert table.family == 6
    assert table.chains['INPUT'].policy == 'drop'
    assert table.chains['INPUT'].rules[0].src[0].text == '2001:db8::/32'


def test_iptables_save_reads_matches_and_targets():
    ruleset = parse_iptables_save(_text('sample-iptables-save.txt'))
    chains = {t.name: t.chains for t in ruleset.tables}
    ssh = chains['filter']['INPUT'].rules[2]
    assert [a.text for a in ssh.src] == ['192.0.2.0/24']
    assert ssh.services[0].dst_ports[0].low == 22
    assert ssh.comment == 'ssh "admin"'
    ping = chains['filter']['INPUT'].rules[3]
    assert (ping.services[0].protocol, ping.services[0].icmp_type) == ('icmp', 8)
    assert (ping.limit_rate, ping.limit_unit) == (5, 'second')
    multiport = chains['filter']['INPUT'].rules[4]
    assert [(p.low, p.high) for p in multiport.services[0].dst_ports] == [
        (80, 80),
        (443, 443),
        (8000, 8080),
    ]
    assert (multiport.action, multiport.jump_target) == ('jump', 'svc')
    dnat = chains['nat']['PREROUTING'].rules[0]
    assert dnat.action == 'dnat'
    assert dnat.nat_addresses[0].text == '192.168.1.10'
    assert dnat.nat_ports.low == 8080


def test_iptables_save_keeps_a_rule_it_cannot_read_and_says_why():
    ruleset = parse_iptables_save(_text('sample-iptables-save.txt'))
    forward = next(t for t in ruleset.tables if t.name == 'filter').chains['FORWARD']
    assert forward.rules[1].unsupported == ['-m recent --set']


def test_iptables_save_reads_the_old_negation_and_names():
    ruleset = parse_iptables_save(
        '*filter\n:INPUT DROP [0:0]\n'
        '-A INPUT -s ! 192.0.2.0/24 -p tcp --dport smtp -j ACCEPT\n'
        '-A INPUT -p icmp --icmp-type network-unknown -j ACCEPT\n'
        '[3:180] -A INPUT -p tcp -m multiport --ports 22,80 -j ACCEPT\n'
        'COMMIT\n'
    )
    smtp, icmp, ports = ruleset.tables[0].chains['INPUT'].rules
    assert smtp.src_negated is True
    assert smtp.services[0].dst_ports[0].low == 25
    assert (icmp.services[0].icmp_type, icmp.services[0].icmp_code) == (3, 6)
    # --ports: the source port or the destination port, two services.
    assert [(bool(s.src_ports), bool(s.dst_ports)) for s in ports.services] == [
        (False, True),
        (True, False),
    ]


def test_iptables_save_reports_the_tables_it_leaves_out():
    ruleset = parse_iptables_save(
        '*mangle\n:PREROUTING ACCEPT [0:0]\n-A PREROUTING -j MARK --set-mark 1\n'
        'COMMIT\n*raw\n:PREROUTING ACCEPT [0:0]\nCOMMIT\n'
    )
    assert ruleset.tables == []
    # The empty raw table every iptables-save lists is not worth a word.
    assert [m[1] for m in ruleset.messages] == [
        'The mangle table is not imported (1 rules): FirewallFabrik builds it '
        'from the marking and classification options of policy rules.'
    ]


def test_a_rate_limit_written_as_hashlimit_is_the_rule_limit():
    ruleset = parse_iptables_save(
        '*filter\n:INPUT DROP [0:0]\n-A INPUT -p tcp --dport 22 -m hashlimit '
        '--hashlimit-above 3/min --hashlimit-burst 5 --hashlimit-name limit_rule_0 '
        '-j DROP\nCOMMIT\n'
    )
    rule = ruleset.tables[0].chains['INPUT'].rules[0]
    assert rule.unsupported == []
    assert (rule.limit_rate, rule.limit_unit, rule.limit_burst, rule.limit_over) == (
        3,
        'minute',
        5,
        True,
    )


