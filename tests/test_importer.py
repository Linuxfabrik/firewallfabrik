    assert ('Policy', 'svc', False) in rule_sets
    assert ('NAT', 'NAT', True) in rule_sets
    # Addresses the ruleset does not name are found at run time.
    assert interfaces == {'lo': False, 'eth0': True, 'eth1': True}


