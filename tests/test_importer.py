def test_a_table_with_filter_and_nat_chains_is_read_as_two():
    """firewalld since 1.0 keeps both in "inet firewalld"."""
    import json

    def chain(name, chain_type, hook):
        return {
            'chain': {
                'family': 'inet',
                'table': 'firewalld',
                'name': name,
                'type': chain_type,
                'hook': hook,
                'prio': 0 if chain_type == 'filter' else -100,
                'policy': 'accept',
            }
        }

    def rule(chain_name, expr):
        return {
            'rule': {
                'family': 'inet',
                'table': 'firewalld',
                'chain': chain_name,
                'expr': expr,
            }
        }

    items = [
        {'table': {'family': 'inet', 'name': 'firewalld'}},
        chain('filter_INPUT', 'filter', 'input'),
        chain('nat_PREROUTING', 'nat', 'prerouting'),
        {'chain': {'family': 'inet', 'table': 'firewalld', 'name': 'nat_PRE_public'}},
        rule('filter_INPUT', [{'reject': None}]),
        rule('nat_PREROUTING', [{'goto': {'target': 'nat_PRE_public'}}]),
    ]
    ruleset = parse_nft_json(json.dumps({'nftables': items}))
    kinds = {t.kind: sorted(t.chains) for t in ruleset.tables}
    assert kinds == {
        'filter': ['filter_INPUT'],
        'nat': ['nat_PREROUTING', 'nat_PRE_public'],
    }


