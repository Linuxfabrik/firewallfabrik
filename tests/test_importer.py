def _nft_listing(rules, family='inet', prio=0):
    """A listing of one input chain holding *rules* (lists of statements)."""
    import json

    items = [
        {'table': {'family': family, 'name': 't'}},
        {
            'chain': {
                'family': family,
                'table': 't',
                'name': 'input',
                'type': 'filter',
                'hook': 'input',
                'prio': prio,
                'policy': 'drop',
            }
        },
    ]
    for expr in rules:
        items.append(
            {'rule': {'family': family, 'table': 't', 'chain': 'input', 'expr': expr}}
        )
    return json.dumps({'nftables': items})


