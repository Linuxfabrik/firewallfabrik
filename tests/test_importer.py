def test_nft_json_reads_tables_chains_sets_and_rules():
    ruleset = parse_nft_json(_text('sample-nft.json'))
    assert ruleset.version == '1.1.6'
    tables = {t.name: t for t in ruleset.tables}
    assert (tables['t'].kind, tables['t'].family) == ('filter', None)
    assert (tables['n'].kind, tables['n'].family) == ('nat', 4)
    assert [a.text for a in ruleset.sets['admins'].addresses] == [
        '192.0.2.0/24',
        '198.51.100.7',
    ]
    rules = tables['t'].chains['input'].rules
    admins = rules[3]
    assert (admins.src_set, admins.comment) == ('admins', 'ssh admins')
    negated = rules[4]
    assert negated.src_negated is True
    assert [a.text for a in negated.src] == ['10.0.0.0/8', '172.16.0.1-172.16.0.9']
    assert negated.states == {'new'}
    either = rules[8]
    assert sorted(s.protocol for s in either.services) == ['tcp', 'udp']
    reset = rules[12]
    assert (reset.action, reset.reject_with) == ('reject', 'tcp-reset')


