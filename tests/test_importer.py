def test_a_state_next_to_a_service_branches(tmp_path):
    db_manager, fw_id, _plan = _import(
        [
            parse_iptables_save(
                '*filter\n:INPUT DROP [0:0]\n'
                '-A INPUT -p tcp --dport 22 -m state --state NEW,ESTABLISHED -j ACCEPT\n'
                'COMMIT\n'
            )
        ],
        'iptables',
        'fw',
    )
    with db_manager.session() as session:
        fw = session.get(Firewall, fw_id)
        nested = next(rs for rs in fw.rule_sets if rs.name.startswith('INPUT_'))
        (inner,) = nested.rules
        target = session.execute(
            sqlalchemy.select(rule_elements.c.target_id).where(
                rule_elements.c.rule_id == inner.id, rule_elements.c.slot == 'srv'
            )
        ).scalar_one()
        service = session.get(CustomService, target)
        assert service.codes['nftables'] == 'ct state established,new'
        outer = next(rs for rs in fw.rule_sets if rs.name == 'Policy').rules[0]
        assert isinstance(outer, PolicyRule)
        assert (outer.options or {}).get('branch_id')


