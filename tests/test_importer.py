IMPORT_DIR = Path(__file__).parent / 'fixtures' / 'import'


def _text(name):
    return (IMPORT_DIR / name).read_text()


def _new_database():
    """A data file the way File > New makes one: Standard plus User."""
    db_manager = DatabaseManager()
    std = (
        Path(str(importlib.resources.files('firewallfabrik') / 'resources'))
        / 'libraries'
        / 'standard.fwf'
    )
    db_manager._load_yaml(std)
    with db_manager.session() as session:
        db = session.scalars(sqlalchemy.select(FWObjectDatabase)).first()
        library = Library(id=uuid.uuid4(), name='User', database=db)
        session.add(library)
        session.flush()
        create_library_folder_structure(session, library.id)
        library_id = library.id
    return db_manager, library_id


def _import(rulesets, platform, name='imported', **kwargs):
    db_manager, library_id = _new_database()
    plan = plan_import(
        db_manager,
        library_id,
        rulesets,
        name,
        platform,
        group_paths=SYSTEM_GROUP_PATHS,
        **kwargs,
    )
    fw_id, unresolved = apply_plan(
        db_manager, library_id, plan, group_paths=SYSTEM_GROUP_PATHS
    )
    assert unresolved == []
    return db_manager, fw_id, plan


def _compile(db_manager, fw_name, tmp_path, platform):
    data_file = tmp_path / 'imported.fwf'
    db_manager.save(data_file)
    db = DatabaseManager()
    db.load(data_file)
    with db.session() as session:
        fw_id = session.scalars(
            sqlalchemy.select(Firewall.id).where(Firewall.name == fw_name)
        ).one()
    if platform == 'ipt':
        from firewallfabrik.platforms.iptables._compiler_driver import (
            CompilerDriver_ipt as Driver,
        )
    else:
        from firewallfabrik.platforms.nftables._compiler_driver import (
            CompilerDriver_nft as Driver,
        )
    driver = Driver(db)
    driver.wdir = str(tmp_path)
    driver.file_name_setting = f'{fw_name}-{platform}.fw'
    driver.run(cluster_id='', fw_id=str(fw_id), single_rule_id='')
    return driver, tmp_path / f'{fw_name}-{platform}.fw'


def _rules(db_manager, fw_id, rule_set_name):
    with db_manager.session() as session:
        fw = session.get(Firewall, fw_id)
        rule_set = next(rs for rs in fw.rule_sets if rs.name == rule_set_name)
        rules = sorted(rule_set.rules, key=lambda r: r.position)
        result = []
        for rule in rules:
            rows = session.execute(
                sqlalchemy.select(
                    rule_elements.c.slot, rule_elements.c.target_id
                ).where(rule_elements.c.rule_id == rule.id)
            ).all()
            result.append((dict(rule.options or {}), rule.comment, rows))
        return result


